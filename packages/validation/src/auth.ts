import { z } from "zod";

/** Employee code format, e.g. "PBS-0012". Input is case-insensitive and normalised to upper case. */
export const EMPLOYEE_CODE_PATTERN = /^PBS-\d{3,5}$/;

export const employeeCodeSchema = z
  .string()
  .trim()
  .min(1, "Employee ID is required")
  .transform((value) => value.toUpperCase())
  .pipe(z.string().regex(EMPLOYEE_CODE_PATTERN, "Use the format PBS-0000"));

/**
 * Password rules for client-side form validation only.
 * The apps never store passwords; hashing is delegated to Supabase Auth.
 */
export const passwordSchema = z
  .string()
  .min(8, "Password must be at least 8 characters")
  .max(128, "Password is too long");

export const employeeLoginSchema = z.object({
  employeeCode: employeeCodeSchema,
  password: passwordSchema,
});
export type EmployeeLoginInput = z.input<typeof employeeLoginSchema>;
export type EmployeeLoginPayload = z.output<typeof employeeLoginSchema>;

export const adminLoginSchema = z.object({
  email: z.string().trim().min(1, "Email is required").pipe(z.email("Enter a valid email address")),
  password: passwordSchema,
});
export type AdminLoginInput = z.input<typeof adminLoginSchema>;
export type AdminLoginPayload = z.output<typeof adminLoginSchema>;

/**
 * Policy for NEW passwords set by an administrator: at least 12 characters with
 * letters and digits. Supabase Auth hashes it; PBS Attend never stores it.
 */
export const newPasswordSchema = z
  .string()
  .min(12, "Password must be at least 12 characters")
  .max(128, "Password is too long")
  .refine((v) => /[A-Za-z]/.test(v) && /\d/.test(v), "Password must contain letters and digits");

export const userRoleSchema = z.enum(["super_admin", "admin", "manager", "employee"]);

const optionalText = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .transform((v) => (v === "" ? undefined : v))
    .optional();

/**
 * Server-side input for creating an employee account. Strict: unknown keys such as a
 * client-supplied profile id are rejected. The profile id is always generated by the server.
 */
export const createEmployeeSchema = z.strictObject({
  employeeCode: employeeCodeSchema,
  fullName: z.string().trim().min(1, "Full name is required").max(120),
  password: newPasswordSchema,
  role: userRoleSchema.default("employee"),
  email: z.string().trim().max(254).pipe(z.email("Enter a valid email address")).optional(),
  department: optionalText(80),
  designation: optionalText(80),
});
export type CreateEmployeeInput = z.output<typeof createEmployeeSchema>;

/** Flattens a zod error into `{ field: firstMessage }` for form display. */
export function fieldErrors(error: z.ZodError): Record<string, string> {
  const out: Record<string, string> = {};
  for (const issue of error.issues) {
    const key = issue.path.join(".") || "_form";
    out[key] ??= issue.message;
  }
  return out;
}
